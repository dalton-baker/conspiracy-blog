            <h3><strong>S</strong> — Single Cryptid Responsibility</h3>
            <p><em>&quot;Each creature should haunt only one domain...&quot;</em></p>
            <p>A cryptid should only have one reason to awaken from the abyss. When a vampire manages the crypt and also handles blood transactions, chaos ensues.</p>
            <h3><strong>O</strong> — Open-Cursed, Closed-Hexed</h3>
            <p><em>&quot;The arcane spell must be open to new rituals but resistant to malevolent upgrades...&quot;</em></p>
            <p>Design your spells to allow the summoning of new horrors without disturbing the eldritch horrors already lurking.</p>
            <h3><strong>L</strong> — Liskov’s Necromantic Substitution</h3>
            <p><em>&quot;A familiar should always obey its master&#39;s dark intentions...&quot;</em></p>
            <p>Derived horrors must be able to seamlessly replace their eldritch ancestors without breaking the summoning circle.</p>
            <h3><strong>I</strong> — Interface Seance</h3>
            <p><em>&quot;Summon only the spirits you need, lest you invite unwelcome ghosts...&quot;</em></p>
            <p>Entities should not be forced to interact with specters they do not wish to summon. Request only the potions and spells you actually need.</p>
            <h3><strong>D</strong> — Dependency on the Dark Arts</h3>
            <p><em>&quot;Rely not on specific necromancers, but on the dark forces they channel...&quot;</em></p>
            <p>Depend on the shadowy forces of abstraction rather than summoning direct demonic entities, ensuring flexibility when new dark lords rise.</p>
            <hr>
            <p><em>May your code be spooky yet maintainable</em></p>
