            <h2 class="card-title">The Empire State Building Grew Again</h2>
            <p class="mb-0 text-warning">November 3, 2025</p>
        </div>
        <article class="card-body markup-content">
            <p>For the first time in over a decade, the Empire State Building has gotten
            taller. According to satellite altimetry data verified by multiple independent sources, the skyscraper
            increased in height by <strong>34 feet</strong> between last Monday and Sunday night.</p>

            <p>That might not sound like much, but it marks the end of a <em>562-week streak</em> of absolute structural
                stillness — no measurable growth, no shrinkage, nothing. Until now.</p>

            <p>The last time we recorded a growth event was in early 2014, when the building rose an estimated
                <strong>28 to 29 feet</strong>. At the time, it was dismissed as an atmospheric anomaly, a calibration
                issue, or “data corruption.” But this week’s increase can't be dismissed so easily, and there’s no sign
                of a simple explanation.</p>

            <h5>No Structural Work, No Permits, No Explanation</h5>

            <p>There have been no construction permits issued, no scaffolding seen, and no changes to the official
                height reported by the city. Yet laser-based measurements, GPS reflection data, and even old-fashioned
                theodolite readings from ground level all agree — the Empire State Building is now <strong>1,486 feet
                    tall</strong>, up from the official 1,452.</p>

            <p>Several researchers have noted that the steel framework seems to be “self-adjusting,” as if the
                building’s internal tension is redistributing itself upward. Others argue this could be a new phase in
                the so-called <em>“Vertical Creep Phenomenon”</em> — a term coined after smaller skyscrapers in Midtown
                Manhattan were observed subtly shifting in height cycles over long periods.</p>

            <h5>Something Is Growing Beneath the City</h5>

            <p>Some theories suggest that the change originates underground. If the foundation is moving — rising,
                expanding, or being pushed up — the effect would manifest exactly as this height gain. But soil data
                doesn’t show uplift. In fact, the bedrock beneath Manhattan has been stable for centuries.</p>

            <p>Unless, of course, the growth isn’t geological at all.</p>

            <h5>The Building That Refuses to Stay Still</h5>

            <p>For now, the cause is unknown. City engineers refused to comment. Whatever’s driving the Empire State
                Building to reach higher — whether mechanical, biological, or something else entirely — it’s waking up
                again.</p>

            <p><em>Keep watching the skyline. It’s not done growing.</em></p>
